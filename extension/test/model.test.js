// Straight transcription of the ORIGINAL (pre-optimisation) forward pass: the reference the
// cached-table / pad-collapse implementation must reproduce.
function naiveForward(manifest, W, url) {
  const tensor = (n) => { const t = manifest.tensors.find((x) => x.name === n); return W.subarray(t.offset, t.offset + t.size); };
  const L = manifest.maxLen, D = manifest.embedDim, F = manifest.filters, emb = tensor("emb");
  const seq = new Uint8Array(L); seq.set(new TextEncoder().encode(url).subarray(0, L));
  const z = new Float32Array(manifest.kernels.length * F);
  manifest.kernels.forEach((k, b) => {
    const w = tensor(`conv${k}_w`), bias = tensor(`conv${k}_b`);
    for (let f = 0; f < F; f++) {
      let maxv = 0;
      for (let p = 0; p < L - k + 1; p++) {
        let s = bias[f];
        for (let i = 0; i < k; i++) for (let c = 0; c < D; c++) s += emb[seq[p + i] * D + c] * w[i * D * F + c * F + f];
        if (s > maxv) maxv = s;
      }
      z[b * F + f] = maxv;
    }
  });
  const dense = (x, w, bb, o, relu) => { const out = new Float32Array(o); for (let j = 0; j < o; j++) { let s = bb[j]; for (let i = 0; i < x.length; i++) s += x[i] * w[i * o + j]; out[j] = relu ? Math.max(0, s) : s; } return out; };
  const h1 = dense(z, tensor("fc1_w"), tensor("fc1_b"), manifest.fc[0], true);
  const h2 = dense(h1, tensor("fc2_w"), tensor("fc2_b"), manifest.fc[1], true);
  const out = dense(h2, tensor("phish_prob_w"), tensor("phish_prob_b"), 1, false);
  return 1 / (1 + Math.exp(-out[0]));
}

test("JS forward matches the NumPy runtime (reference probabilities generated by uniphish.url.model)", () => {
  const { manifest, W } = loadModel();
  const ref = readJson("test/fixtures_model_parity.json");
  assert.ok(ref.urls.length >= 15);
  ref.urls.forEach((u, i) => {
    assert.ok(Math.abs(M.forward(manifest, W, u) - ref.probs[i]) < 1e-4, `parity failed for ${JSON.stringify(u.slice(0, 60))}`);
  });
});

test("optimised forward equals the original naive forward pass", () => {
  const { manifest, W } = loadModel();
  const urls = ["https://example.com/", "http://paypal.com.secure-login.example/verify", "https://пример.example/вход",
    "x", "", "https://example.com/" + "b".repeat(650)];
  for (const u of urls) assert.ok(Math.abs(M.forward(manifest, W, u) - naiveForward(manifest, W, u)) < 1e-5, u.slice(0, 40));
});

test("scoring is fast enough for per-link use", () => {
  const { manifest, W } = loadModel();
  M.forward(manifest, W, "https://warmup.example/");
  const t0 = process.hrtime.bigint();
  for (let i = 0; i < 100; i++) M.forward(manifest, W, `https://shop${i}.example.com/product?id=${i}&ref=abc`);
  const msPer = Number(process.hrtime.bigint() - t0) / 1e6 / 100;
  assert.ok(msPer < 20, `too slow: ${msPer.toFixed(2)} ms/url`);
});

test("setWeights rejects a truncated weights file", () => {
  const { manifest, W } = loadModel();
  assert.throws(() => new M.UniPhishModel().setWeights(manifest, W.subarray(0, 1000)), /too short/);
});

test("occlusion saliency: shapes, determinism and multi-byte handling", () => {
  const { model } = loadModel();
  const url = "http://paypal.com.secure-login.example/verify";
  const r1 = Sal.occlusion(model, url), r2 = Sal.occlusion(model, url);
  assert.equal(r1.chars.length, [...url].length);
  assert.deepEqual(r1.chars.map((c) => c.delta), r2.chars.map((c) => c.delta));
  const spans = Sal.topSpans(url, r1);
  for (const s of spans) assert.equal(url.slice(s.start, s.end), s.text);
  // multi-byte: indices are UTF-16 offsets and every code point is covered exactly once
  const u2 = "https://pаypal.example/😀x";
  const r3 = Sal.occlusion(model, u2);
  assert.equal(r3.chars.map((c) => c.char).join(""), u2);
  assert.equal(r3.chars[r3.chars.length - 1].index, u2.length - 1);
});

test("saliency respects maxChars (unscored tail has zero delta)", () => {
  const { model } = loadModel();
  const r = Sal.occlusion(model, "https://example.com/" + "a".repeat(100), 10);
  assert.ok(r.chars.slice(10).every((c) => c.delta === 0 && !c.scored));
});
