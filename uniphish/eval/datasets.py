DATASET_NAMES = ("lookalike", "benign", "urls", "smishing", "injection", "email")

MALICIOUS, BENIGN = 1, 0

_ASCII_TLDS = ("test", "example", "invalid")
# IETF-reserved test TLDs (RFC 2606 / 6761 and the IDN test TLDs); used to tag items whose
