"""Labelled, reproducible, SYNTHETIC-or-reserved benchmark sets.

Why this module exists: a detector is only as credible as the evidence for it, and the
evidence is only as credible as the data. These sets are deliberately small, fully
deterministic (seeded) and safe to commit: **no live malicious URL appears anywhere**.

* Phishing-style hosts live under reserved TLDs (``.test``, ``.example``, ``.invalid``
  and the IETF-reserved internationalised test TLDs such as ``.测试`` / ``.испытание``),
  so they can never resolve to anything.
* Benign URLs are either reserved names, ordinary well-known sites that are plainly
  legitimate, or invented small-site structures under reserved names.
* Text corpora (``_corpus.py``) use fictional phone numbers and ``.test`` links.

Sets (``DATASET_NAMES``)
------------------------
``lookalike``  malicious-only: homoglyph (Cyrillic / Greek / Armenian / Latin-extended),
               IDN, punycode, typo/bit/digit squats, combosquats, subdomain stuffing,
               path deception, userinfo ("@") tricks and native-script (CJK, Arabic,
               Devanagari, Hangul, Cyrillic) brand impostors.
``benign``     benign-only and **adversarial for false positives**: reserved names,
               brands' own login pages, long legitimate URLs, OAuth flows, legitimate
               IDNs, LOTS-hosted-but-harmless pages, brand names in unrelated legitimate
               paths, and a long tail of small legitimate sites that no reputation list
               would vouch for.
``urls``       ``lookalike`` + ``benign`` (the headline URL benchmark).
``smishing``   SMS/chat text, malicious vs benign, multilingual.
``injection``  prompt-injection (direct / indirect / obfuscated, text and HTML) vs benign.
``email``      spoofed / lookalike / BEC / callback vs authenticated, legitimate mail.

Honest caveats (also surfaced in every report): the malicious URLs are *generated by the
same families of transformation the detector was designed around*, so recall here is an
optimistic ceiling, not a field estimate; and the benign sets are not a sample of real
traffic. See ``docs/evaluation.md`` and ``docs/paper_vs_reality.md``.
"""

