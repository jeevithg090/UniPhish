def build_benign_set(
    per_category: int = DEFAULT_PER_CATEGORY, seed: int = DEFAULT_SEED
) -> list[EvalItem]:
    """Build the benign URL set (hand-picked plus seeded generation)."""
    rng = random.Random(seed + 1)
    g = _Gen("benign", BENIGN)

    for i, h in enumerate(
        (
            "example.com",
            "www.example.org",
            "docs.example.net",
            "shop.test",
            "mail.example",
            "www.example.com",
            "status.example.org",
            "api.example.net",
            "blog.example.com",
            "wiki.test",
        ),
        start=1,
    ):
        for path in ("/", "/about", f"/docs/page-{i}?lang=en"):
            if g.count("reserved") < per_category * 2:
                g.add("reserved", f"https://{h}{path}")
    for u in _BRAND_OFFICIAL:
        g.add("brand_official", u, tags=("hard",), note="the brand's own sign-in / account page")
    for u in _LOTS_BENIGN:
        g.add(
            "lots_benign", u, tags=("hard",), note="legitimate content on a free-hosting platform"
        )
    for u in _BRAND_CONTEXT:
        g.add(
            "brand_in_context",
            u,
            tags=("hard",),
            note="brand name inside an unrelated legitimate URL",
        )
    for u in _MULTISCRIPT_LEGIT:
        g.add("multiscript_legit", u, note="mainstream non-Latin or regional sites")
    for u in _LEGIT_IDN:
        g.add("legit_idn", u, tags=("hard",), note="legitimate internationalised host")

    def long_url(r: random.Random) -> str:
        base, keys = r.choice(_LONG_BASES)
        parts = []
        for k in keys:
            parts.append(f"{k}={'-'.join(r.choice(_WORDS) for _ in range(r.randrange(2, 6)))}")
        parts.append("session=" + "".join(r.choice("0123456789abcdef") for _ in range(32)))
        parts.append("ref=" + "-".join(r.choice(_WORDS) for _ in range(r.randrange(8, 20))))
        return base + "?" + "&".join(parts)

    for _ in range(per_category):
        g.add("long_legit", long_url(rng), tags=("hard",), note="long legitimate URL")
    for _ in range(max(2, per_category // 2)):
        state = "".join(rng.choice("abcdefghijklmnopqrstuvwxyz0123456789") for _ in range(40))
        g.add(
            "oauth_flow",
            "https://www.example.com/oauth/authorize?response_type=code&client_id="
            f"{rng.randrange(10**5, 10**6)}&redirect_uri=https%3A%2F%2Fapp.example.org%2Fcallback"
            f"&scope=openid%20profile%20email&state={state}",
            tags=("hard",),
            note="legitimate OAuth authorisation URL (contains a redirect parameter)",
        )

    while g.count("long_tail") < per_category * 2:
        tail = f"{rng.choice(_TAIL_NOUNS)}-{rng.choice(_WORDS)}"
        host = (
            f"www.{tail}.{rng.choice(_ASCII_TLDS)}"
            if rng.random() < 0.5
            else f"www.{tail}.{rng.choice(('example.com', 'example.org', 'example.net'))}"
        )
        g.add(
            "long_tail",
            f"https://{host}/{rng.choice(_TAIL_PAGES)}",
            note="small legitimate site with no reputation signal",
        )
    while g.count("long_tail_login") < per_category:
        sub_ = rng.choice(("members", "portal", "my", "app"))
        dom = rng.choice(("example.com", "example.org", "example.net"))
        host = f"{sub_}.{rng.choice(_TAIL_NOUNS)}.{dom}"
        g.add(
            "long_tail_login",
            f"https://{host}/{rng.choice(_TAIL_LOGIN)}",
            tags=("hard",),
            note="legitimate small-site sign-in page (login vocabulary, no brand)",
        )
    return g.items


