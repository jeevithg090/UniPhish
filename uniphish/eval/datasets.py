def _rows_to_items(dataset: str, rows: Sequence[C.Row], kind: str) -> list[EvalItem]:
    n: Counter[str] = Counter()
    out = []
    for r in rows:
        n[r.category] += 1
        out.append(
            EvalItem(
                id=f"{dataset}:{r.category}:{n[r.category]:03d}",
                dataset=dataset,
                category=r.category,
                label=r.label,
                spec=ArtifactSpec(kind, r.text),
                lang=r.lang,
                script=_script_of(r.text),
                tags=r.tags,
            )
        )
    return out


def _script_of(text: str) -> str:
    """Coarse dominant script by Unicode block (labelling only; not used by detectors)."""
    counts: Counter[str] = Counter()
    for ch in text:
        o = ord(ch)
        if ch.isascii() or not ch.isalpha():
            counts["Latn"] += 1 if ch.isalpha() else 0
        elif 0x0400 <= o < 0x0530:
            counts["Cyrl"] += 1
        elif 0x0600 <= o < 0x0700:
            counts["Arab"] += 1
        elif 0x0900 <= o < 0x0980:
            counts["Deva"] += 1
        elif 0xAC00 <= o < 0xD7B0 or 0x1100 <= o < 0x1200:
            counts["Hang"] += 1
        elif 0x3040 <= o < 0x3100:
            counts["Jpan"] += 1
        elif 0x4E00 <= o < 0xA000:
            counts["Hani"] += 1
        else:
            counts["Latn"] += 1
    return counts.most_common(1)[0][0] if counts else "Latn"


def build_smishing_set() -> list[EvalItem]:
    """Curated SMS / chat set (malicious vs benign, multilingual)."""
    return _rows_to_items("smishing", C.SMISHING, "text")


def build_email_set() -> list[EvalItem]:
    """Curated e-mail set: spoofed / look-alike / BEC / callback versus authentic mail."""
    return _rows_to_items("email", C.email_rows(), "email")


def build_injection_set(seed: int = DEFAULT_SEED) -> list[EvalItem]:
    """Prompt-injection set: direct, indirect (text and HTML) and obfuscated, plus benign."""
    rng = random.Random(seed + 2)
    items: list[EvalItem] = []
    n: Counter[str] = Counter()

    def add(
        category: str,
        label: int,
        kind: str,
        value: str,
        *,
        lang: str = "en",
        tags: tuple[str, ...] = (),
        note: str = "",
    ) -> None:
        n[category] += 1
        items.append(
            EvalItem(
                id=f"injection:{category}:{n[category]:03d}",
                dataset="injection",
                category=category,
                label=label,
                spec=ArtifactSpec(
                    kind, value, url="https://pages.example/" if kind == "page" else None
                ),
                lang=lang,
                script=_script_of(value),
                tags=tags,
                note=note,
            )
        )

    for cat, lang, text in C.INJECTION_PAYLOADS:
        add(f"direct_{cat}" if lang == "en" else "direct_multilingual", 1, "text", text, lang=lang)
    for text in C.INDIRECT_TEXTS:
        add(
            "indirect_text",
            1,
            "text",
            text,
            note="instruction hidden in otherwise ordinary content",
        )
    for cat, frag in C.HTML_INDIRECT:
        add(
            cat,
            1,
            "page",
            C.html_page(
                "Community news",
                body=frag if not frag.startswith("<meta") else "",
                head=frag if frag.startswith("<meta") else "",
            ),
            note="hidden surface in an HTML page",
        )
    bases = [t for c, lang, t in C.INJECTION_PAYLOADS if lang == "en"]
    cover = "Here is the weather summary for tomorrow: mild with light showers in the afternoon."
    encoders: list[tuple[str, Callable[[str], str]]] = [
        ("obf_tag_smuggling", lambda t: cover + C.tag_encode(t)),
        ("obf_zero_width", lambda t: C.zero_width_split(t)),
        ("obf_homoglyph", lambda t: C.homoglyph_swap(t)),
        ("obf_base64", C.b64_wrap),
        ("obf_hex", C.hex_wrap),
    ]
    for cat, enc in encoders:
        picks = rng.sample(range(len(bases)), 3)
        for i in sorted(picks):
            add(
                cat,
                1,
                "text",
                enc(bases[i]),
                tags=("hard",),
                note="obfuscated variant of a direct payload",
            )
    for r in C.INJECTION_BENIGN:
        add(r.category, 0, "text", r.text, lang=r.lang, tags=r.tags)
    for cat, html, tags in C.benign_html_pages():
        add(cat, 0, "page", html, tags=tags)
    return items


