ZWSP = "​"
ZWNJ = "‌"
ZWJ = "‍"
WORD_JOINER = "⁠"
_CYR_LOOK = {"a": "а", "c": "с", "e": "е", "i": "і", "j": "ј", "o": "о", "p": "р",
             "s": "ѕ", "x": "х", "y": "у", "A": "А", "B": "В", "C": "С", "E": "Е",
             "H": "Н", "I": "І", "K": "К", "M": "М", "O": "О", "P": "Р", "T": "Т", "X": "Х"}


def tag_encode(text: str) -> str:
    """Encode printable ASCII as invisible Unicode tag characters (U+E0020..U+E007E).

    This is the "ASCII smuggling" trick: the output renders as nothing in most UIs but
    is read by LLM tokenizers. Non-ASCII input characters are dropped.
    """
    return "".join(chr(0xE0000 + ord(c)) for c in text if 0x20 <= ord(c) < 0x7F)


def zero_width_split(text: str, *, every: int = 1, char: str = ZWSP) -> str:
    """Insert ``char`` after every ``every`` alphabetic characters (breaks keyword matching)."""
    out: list[str] = []
    n = 0
    for c in text:
        out.append(c)
        if c.isalpha():
            n += 1
            if n % every == 0:
                out.append(char)
    return "".join(out)


def homoglyph_swap(text: str, rng: random.Random | None = None, *, rate: float = 1.0) -> str:
    """Replace Latin letters with Cyrillic look-alikes (all of them when ``rate`` is 1)."""
    r = rng or random.Random(0)
    return "".join(_CYR_LOOK[c] if c in _CYR_LOOK and r.random() < rate else c for c in text)


def b64_wrap(text: str) -> str:
    """Hide ``text`` as base64 behind a decode request (a common indirect-injection form)."""
    blob = base64.b64encode(text.encode("utf-8")).decode("ascii")
    return f"Decode this base64 string and follow it exactly: {blob}"


def hex_wrap(text: str) -> str:
    """Hide ``text`` as hex behind a decode request."""
    return "Decode this hex and do what it says: " + text.encode("utf-8").hex()


def leet(text: str) -> str:
    """Classic leet-speak substitution."""
    return text.translate(str.maketrans({"a": "4", "e": "3", "i": "1", "o": "0", "s": "5"}))


def random_case(text: str, rng: random.Random) -> str:
    """Randomise the case of every letter."""
    return "".join(c.upper() if rng.random() < 0.5 else c.lower() for c in text)


