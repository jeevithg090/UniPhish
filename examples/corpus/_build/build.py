"""Regenerate the sample corpus from the data modules in this folder.

Run from the repository root::

    .venv/bin/python examples/corpus/_build/build.py            # write everything
    .venv/bin/python examples/corpus/_build/build.py --check    # exit 1 if files are stale

Everything written is deterministic (no timestamps, no randomness), so ``--check`` is a
reliable freshness test. The data modules hold the content; this script only serialises
it into ``urls.jsonl``, ``texts.jsonl``, ``emails/``, ``pages/``, ``files/`` and the
``manifest.yaml`` index, plus the per-folder READMEs.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT))

from _build.data_emails import EMAILS, quishing_email  # noqa: E402
from _build.data_files import build_files  # noqa: E402
from _build.data_pages import PAGES  # noqa: E402
from _build.data_texts import TEXTS  # noqa: E402
from _build.data_urls import URLS  # noqa: E402

SCHEMA_VERSION = 1
LABEL_HELP = "malicious = phishing / BEC / prompt injection; benign = legitimate content"


def _jsonl(rows: list[dict], keys: tuple[str, ...]) -> str:
    out = []
    for r in rows:
        rec = {k: r[k] for k in keys if k in r}
        out.append(json.dumps(rec, ensure_ascii=False, separators=(", ", ": ")))
    return "\n".join(out) + "\n"


def _yaml_scalar(v: object) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return json.dumps(v, ensure_ascii=False)  # JSON strings are valid YAML scalars


def _manifest(entries: list[dict]) -> str:
    keys = ("id", "kind", "label", "category", "lang", "script", "headline_signal", "hard",
            "source", "path", "url", "filename")
    lines = [
        "# Index of every item in the sample corpus. GENERATED by _build/build.py; do not "
        "edit by hand.",
        f"# {LABEL_HELP}.",
        "# headline_signal: the signal id the engine is expected to emit (null = none "
        "expected).",
        "# hard: true = deliberately difficult offline; excluded from strict assertions.",
        f"version: {SCHEMA_VERSION}",
        "items:",
    ]
    for e in entries:
        body = ", ".join(f"{k}: {_yaml_scalar(e[k])}" for k in keys
                         if k in e and (e[k] is not None or k == "headline_signal"))
        lines.append("  - {" + body + "}")
    return "\n".join(lines) + "\n"


def _readme(title: str, rows: list[tuple[str, str, str, str]], intro: str) -> str:
    out = [f"# {title}", "", intro, "", "| File | Label | Category | What it shows |",
           "| --- | --- | --- | --- |"]
    out += [f"| `{a}` | {b} | {c} | {d} |" for a, b, c, d in rows]
    out += ["", "All content is synthetic and inert; hosts are reserved (`.test`, `.example`, "
            "`example.com`). Generated by `examples/corpus/_build/build.py`.", ""]
    return "\n".join(out)


def render() -> dict[str, bytes]:
    """Return {relative path: bytes} for the whole corpus."""
    files: dict[str, bytes] = {}
    items = build_files()
    qr = next(f for f in items if f["id"] == "file-qr-phish")["data"]
    emails = EMAILS + [quishing_email(qr)]
    manifest: list[dict] = []

    files["urls.jsonl"] = _jsonl(URLS, ("id", "input", "label", "category", "note",
                                        "expected_techniques", "headline_signal", "script",
                                        "hard")).encode()
    for r in URLS:
        manifest.append(dict(id=r["id"], kind="url", label=r["label"], category=r["category"],
                             lang="und", script=r["script"], headline_signal=r["headline_signal"],
                             hard=r["hard"], source="urls.jsonl"))
    files["texts.jsonl"] = _jsonl(TEXTS, ("id", "input", "label", "category", "lang", "note",
                                          "expected_techniques", "headline_signal",
                                          "hard")).encode()
    for r in TEXTS:
        manifest.append(dict(id=r["id"], kind="text", label=r["label"], category=r["category"],
                             lang=r["lang"], headline_signal=r["headline_signal"],
                             hard=r["hard"], source="texts.jsonl"))
    rows = []
    for r in emails:
        crlf = r["raw"].replace("\r\n", "\n").replace("\n", "\r\n")
        files[f"emails/{r['filename']}"] = crlf.encode()
        manifest.append(dict(id=r["id"], kind="email", label=r["label"], category=r["category"],
                             lang="en", headline_signal=r["headline_signal"], hard=r["hard"],
                             path=f"emails/{r['filename']}"))
        rows.append((r["filename"], r["label"], r["category"], r["note"]))
    files["emails/README.md"] = _readme(
        "Synthetic e-mail samples", rows,
        "Each `.eml` maps to the label below. " + LABEL_HELP + ".").encode()
    rows = []
    for r in PAGES:
        files[f"pages/{r['filename']}"] = r["html"].encode()
        manifest.append(dict(id=r["id"], kind="page", label=r["label"], category=r["category"],
                             lang="en", headline_signal=r["headline_signal"], hard=r["hard"],
                             path=f"pages/{r['filename']}", url=r["url"]))
        rows.append((r["filename"], r["label"], r["category"], r["note"]))
    files["pages/README.md"] = _readme(
        "Synthetic HTML pages", rows,
        "Defanged pages; the `url` each was 'served from' is recorded in `manifest.yaml`. "
        + LABEL_HELP + ".").encode()
    rows = []
    for r in items:
        files[f"files/{r['stored']}"] = r["data"]
        manifest.append(dict(id=r["id"], kind="file", label=r["label"], category=r["category"],
                             lang="en", headline_signal=r["headline_signal"], hard=r["hard"],
                             path=f"files/{r['stored']}", filename=r["presented"]))
        rows.append((r["stored"], r["label"], r["category"], r["note"]))
    files["files/README.md"] = _readme(
        "Inert file samples", rows,
        "Stored names are safe on disk; the *presented* file name an analyser is given is "
        "recorded in `manifest.yaml` (`filename`). No real malware, macro or exploit is "
        "included. " + LABEL_HELP + ".").encode()
    files["manifest.yaml"] = _manifest(manifest).encode()
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify files are up to date")
    args = ap.parse_args(argv)
    stale = []
    for rel, data in render().items():
        p = ROOT / rel
        if args.check:
            if not p.exists() or p.read_bytes() != data:
                stale.append(rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(data)
    if args.check:
        for rel in stale:
            print(f"stale: {rel}")
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
