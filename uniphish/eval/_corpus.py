_DATE = "Mon, 10 Nov 2025 10:00:00 +0000"


def a_pass(domain: str, mx: str = "mx.example.net") -> str:
    """An Authentication-Results header showing aligned SPF+DKIM+DMARC pass."""
    return (f"Authentication-Results: {mx}; spf=pass smtp.mailfrom={domain}; "
            f"dkim=pass header.d={domain}; dmarc=pass header.from={domain}")


def a_fail(domain: str, mx: str = "mx.example.net") -> str:
    """An Authentication-Results header showing failed SPF and DMARC."""
    return (f"Authentication-Results: {mx}; spf=fail smtp.mailfrom={domain}; dkim=none; "
            f"dmarc=fail header.from={domain}")


def eml(frm: str, subject: str, body: str, *, to: str = "reader@example.com",
        auth: str | None = None, reply_to: str | None = None, ret: str | None = None,
        html: str | None = None, extra: tuple[str, ...] = (), lang: str = "en") -> str:
    """Compose a minimal, valid RFC 5322 message (plain or multipart/alternative)."""
    addr = frm[frm.rfind("<") + 1:].rstrip(">") if "<" in frm else frm
    dom = addr.rsplit("@", 1)[-1]
    h = [f"From: {frm}", f"To: {to}", f"Subject: {subject}", f"Date: {_DATE}",
         f"Message-ID: <{zlib.crc32(subject.encode()) % 10**8:08d}.eval@{dom}>"]
    if reply_to:
        h.append(f"Reply-To: {reply_to}")
    if ret:
        h.append(f"Return-Path: <{ret}>")
    if auth:
        h.append(auth)
    h.extend(extra)
    h.append("MIME-Version: 1.0")
    if html is None:
        h.append('Content-Type: text/plain; charset="utf-8"')
        h.append("Content-Transfer-Encoding: 8bit")
        return "\n".join(h) + "\n\n" + body + "\n"
    b = "=_eval_boundary_01"
    h.append(f'Content-Type: multipart/alternative; boundary="{b}"')
    parts = [f"--{b}", 'Content-Type: text/plain; charset="utf-8"', "", body,
             f"--{b}", 'Content-Type: text/html; charset="utf-8"', "", html, f"--{b}--", ""]
    return "\n".join(h) + "\n\n" + "\n".join(parts)


