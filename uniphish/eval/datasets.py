def load_items(
    name: str, *, seed: int = DEFAULT_SEED, per_category: int = DEFAULT_PER_CATEGORY
) -> list[EvalItem]:
    """Return the labelled items of dataset ``name`` (see :data:`DATASET_NAMES`).

    ``seed`` and ``per_category`` only affect the generated URL sets; the curated text
    corpora are fixed. The same arguments always produce the same items in the same order.
    """
    if name == "lookalike":
        return build_lookalike_set(per_category, seed)
    if name == "benign":
        return build_benign_set(per_category, seed)
    if name == "urls":
        return build_lookalike_set(per_category, seed) + build_benign_set(per_category, seed)
    if name == "smishing":
        return build_smishing_set()
    if name == "injection":
        return build_injection_set(seed)
    if name == "email":
        return build_email_set()
    raise ValueError(f"unknown dataset {name!r}; choose from {', '.join(DATASET_NAMES)}")


def load_dataset(
    name: str, *, seed: int = DEFAULT_SEED, per_category: int = DEFAULT_PER_CATEGORY
) -> list[tuple[ArtifactSpec, int]]:
    """Return ``[(artifact_spec, label), ...]`` for dataset ``name`` (1 = malicious)."""
    return [(i.spec, i.label) for i in load_items(name, seed=seed, per_category=per_category)]


def dataset_sha256(items: Iterable[EvalItem]) -> str:
    """Content hash of a dataset (ids, labels, payloads) for reproducibility claims."""
    h = hashlib.sha256()
    for it in items:
        h.update(
            json.dumps(
                [it.id, it.label, it.spec.kind, it.spec.value, it.spec.url], ensure_ascii=False
            ).encode("utf-8")
        )
        h.update(b"\n")
    return h.hexdigest()


def summarize(items: Sequence[EvalItem]) -> dict[str, Any]:
    """Counts by label, category, language and script (for the dataset datasheet)."""
    cats: dict[str, dict[str, int]] = {}
    for it in items:
        c = cats.setdefault(it.category, {"n": 0, "malicious": 0, "benign": 0})
        c["n"] += 1
        c["malicious" if it.label else "benign"] += 1
    return {
        "n": len(items),
        "malicious": sum(i.label for i in items),
        "benign": sum(1 - i.label for i in items),
        "hard": sum(i.hard for i in items),
        "categories": cats,
        "languages": dict(Counter(i.lang for i in items)),
        "scripts": dict(Counter(i.script for i in items)),
        "sha256": dataset_sha256(items),
    }
