@dataclass(frozen=True)
class ArtifactSpec:
    """A serialisable recipe for an :class:`~uniphish.core.types.Artifact`.

    ``kind`` is one of ``url`` / ``text`` / ``email`` / ``page``; ``value`` is the URL,
    text, raw RFC 5322 message or HTML; ``url`` is the origin URL of a ``page``.
    """

    kind: str
    value: str
    url: str | None = None

    def to_artifact(self) -> Artifact:
        """Build the real artifact (applies the artifact size limits)."""
        if self.kind == "url":
            return Artifact.from_url(self.value)
        if self.kind == "text":
            return Artifact.from_text(self.value)
        if self.kind == "email":
            return Artifact.from_email(self.value)
        if self.kind == "page":
            return Artifact.from_page(self.value, self.url)
        raise ValueError(f"unknown artifact kind {self.kind!r}")

    @property
    def target(self) -> str:
        """Short label for reports (URL or first characters of the content)."""
        if self.kind == "url":
            return self.value
        head = " ".join(self.value.split())
        return head[:100] + ("..." if len(head) > 100 else "")


@dataclass(frozen=True)
class EvalItem:
    """One labelled benchmark item. ``label`` is 1 for malicious, 0 for benign."""

    id: str
    dataset: str
    category: str
    label: int
    spec: ArtifactSpec
    lang: str = "en"
    script: str = "Latn"
    tags: tuple[str, ...] = field(default_factory=tuple)
    note: str = ""

    @property
    def hard(self) -> bool:
        """True for deliberately tricky items (hard negatives / hard positives)."""
        return "hard" in self.tags

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "dataset": self.dataset,
            "category": self.category,
            "label": self.label,
            "kind": self.spec.kind,
            "target": self.spec.target,
            "lang": self.lang,
            "script": self.script,
            "tags": list(self.tags),
            "note": self.note,
        }


# --------------------------------------------------------------------------- #
# URL generation: look-alikes
# --------------------------------------------------------------------------- #
def _swap(label: str, table: dict[str, str], rng: random.Random, k: int) -> str | None:
    pos = [i for i, c in enumerate(label) if c in table]
    if not pos:
        return None
    chosen = set(rng.sample(pos, min(k, len(pos))))
    return "".join(table[c] if i in chosen else c for i, c in enumerate(label))


def _whole_script(label: str, table: dict[str, str]) -> str | None:
    return "".join(table[c] for c in label) if all(c in table for c in label) else None


def _typo(label: str, rng: random.Random) -> str:
    op = rng.choice(("omit", "dup", "swap", "key"))
    i = rng.randrange(1, len(label) - 1)
    if op == "omit":
        return label[:i] + label[i + 1 :]
    if op == "dup":
        return label[:i] + label[i] + label[i:]
    if op == "swap":
        return label[:i] + label[i + 1] + label[i] + label[i + 2 :]
    for row in _KEY_ROWS:
        j = row.find(label[i])
        if j >= 0:
            nb = row[j - 1] if j > 0 else row[j + 1]
            return label[:i] + nb + label[i + 1 :]
    return label[:i] + label[i + 1 :]


def _bitsquat(label: str, rng: random.Random) -> str | None:
    cands = []
    for i, c in enumerate(label):
        for bit in range(7):
            c2 = chr(ord(c) ^ (1 << bit))
            if c2 != c and (c2.isascii() and (c2.islower() or c2.isdigit())):
                cands.append(label[:i] + c2 + label[i + 1 :])
    return rng.choice(cands) if cands else None


def _host_tld(url: str) -> str:
    """Last label of the URL's host (empty if none); labelling only."""
    rest = url.split("://", 1)[-1]
    host = rest.split("/", 1)[0].rsplit("@", 1)[-1].split(":", 1)[0].split("?", 1)[0]
    return host.rsplit(".", 1)[-1].lower()


def _idna(host: str) -> str | None:
    try:
        return host.encode("idna").decode("ascii")
    except UnicodeError:
        return None


def _tld(rng: random.Random) -> str:
    return rng.choice(_ASCII_TLDS)


def _rand_label(rng: random.Random) -> str:
    return (
        rng.choice(("account", "portal", "mail", "cloud", "online", "web", "my", "secure"))
        + "-"
        + rng.choice(("check", "center", "hub", "desk", "zone", "gate", "link"))
        + str(rng.randrange(10, 99))
    )


class _Gen:
    """Collects de-duplicated generated items for one dataset."""

    def __init__(self, dataset: str, label: int) -> None:
        self.dataset, self.label = dataset, label
        self.items: list[EvalItem] = []
        self._seen: set[str] = set()
        self._n: Counter[str] = Counter()

    def add(
        self,
        category: str,
        url: str | None,
        *,
        lang: str = "en",
        script: str = "Latn",
        tags: Iterable[str] = (),
        note: str = "",
    ) -> bool:
        if not url or url in self._seen:
            return False
        self._seen.add(url)
        tags = tuple(tags)
        if _host_tld(url) in RESERVED_TLDS and "reserved_tld" not in tags:
            tags += ("reserved_tld",)
        self._n[category] += 1
        self.items.append(
            EvalItem(
                id=f"{self.dataset}:{category}:{self._n[category]:03d}",
                dataset=self.dataset,
                category=category,
                label=self.label,
                spec=ArtifactSpec("url", url),
                lang=lang,
                script=script,
                tags=tags,
                note=note,
            )
        )
        return True

    def count(self, category: str) -> int:
        return self._n[category]


def _fill(
    gen: _Gen,
    category: str,
    n: int,
    rng: random.Random,
    make: Callable[[random.Random, str], tuple[str, dict[str, Any]] | None],
) -> None:
    """Call ``make(rng, brand)`` until ``n`` unique items were added (bounded retries)."""
    brands = list(BRANDS)
    rng.shuffle(brands)
    tries = 0
    while gen.count(category) < n and tries < n * 40:
        brand = brands[tries % len(brands)]
        tries += 1
        out = make(rng, brand)
        if out:
            gen.add(category, out[0], **out[1])


def build_lookalike_set(
    per_category: int = DEFAULT_PER_CATEGORY, seed: int = DEFAULT_SEED
) -> list[EvalItem]:
    """Generate the malicious look-alike URL set (deterministic for a given seed)."""
    rng = random.Random(seed)
    g = _Gen("lookalike", MALICIOUS)

    def url(host: str, rng: random.Random) -> str:
        return f"https://{host}{rng.choice(_LOGIN_PATHS)}"

    def homoglyph(table: dict[str, str], script: str, k: int):
        def make(r: random.Random, b: str):
            lab = _swap(b, table, r, k)
            return (url(f"{lab}.{_tld(r)}", r), {"script": script}) if lab else None

        return make

    _fill(g, "homoglyph_cyrillic", per_category, rng, homoglyph(_CYR, "Cyrl", 1))
    _fill(g, "homoglyph_cyrillic_multi", per_category, rng, homoglyph(_CYR, "Cyrl", 2))
    _fill(g, "homoglyph_greek", per_category, rng, homoglyph(_GRK, "Grek", 1))
    _fill(g, "homoglyph_armenian", per_category, rng, homoglyph(_ARM, "Armn", 1))
    _fill(g, "homoglyph_latin_ext", per_category, rng, homoglyph(_LATX, "Latn", 1))
    _fill(g, "idn_diacritic", per_category, rng, homoglyph(_DIAC, "Latn", 1))

    def whole(r: random.Random, b: str):
        lab = _whole_script(b, _CYR)
        return (
            (
                url(f"{lab}.{_tld(r)}", r),
                {"script": "Cyrl", "tags": ("hard",), "note": "whole-script Cyrillic label"},
            )
            if lab
            else None
        )

    _fill(g, "idn_whole_script", per_category, rng, whole)

    def puny(r: random.Random, b: str):
        table = r.choice((_CYR, _GRK, _ARM))
        lab = _swap(b, table, r, 1)
        host = _idna(f"{lab}.{_tld(r)}") if lab else None
        return (url(host, r), {"note": "punycode form of an IDN look-alike"}) if host else None

    _fill(g, "idn_punycode", per_category, rng, puny)

    def typo(r: random.Random, b: str):
        return url(f"{_typo(b, r)}.{_tld(r)}", r), {}

    _fill(g, "typosquat", per_category, rng, typo)

    def bit(r: random.Random, b: str):
        lab = _bitsquat(b, r)
        return (url(f"{lab}.{_tld(r)}", r), {}) if lab else None

    _fill(g, "bitsquat", per_category, rng, bit)

    def digit(r: random.Random, b: str):
        lab = _swap(b, _DIGITS, r, 1)
        return (url(f"{lab}.{_tld(r)}", r), {}) if lab else None

    _fill(g, "digit_lookalike", per_category, rng, digit)

    combo = (
        "{b}-secure-login",
        "secure-{b}",
        "{b}-support",
        "login-{b}-verify",
        "{b}-account-update",
        "my{b}-helpdesk",
        "{b}login",
        "{b}-verify",
        "{b}-billing",
    )

    def combosquat(r: random.Random, b: str):
        return url(f"{r.choice(combo).format(b=b)}.{_tld(r)}", r), {}

    _fill(g, "combosquat", per_category, rng, combosquat)

    def stuffing(r: random.Random, b: str):
        return url(
            f"www.{b}.com.{r.choice(_HOST_WORDS)}-check{r.randrange(10, 99)}.{_tld(r)}", r
        ), {}

    _fill(g, "subdomain_stuffing", per_category, rng, stuffing)

    def path_decoy(r: random.Random, b: str):
        return (f"https://{_rand_label(r)}.{_tld(r)}/www.{b}.com{r.choice(_LOGIN_PATHS[:5])}", {})

    _fill(g, "path_deception", per_category, rng, path_decoy)

    def at_trick(r: random.Random, b: str):
        return (
            f"https://www.{b}.com@{_rand_label(r)}.{_tld(r)}{r.choice(_LOGIN_PATHS)}",
            {"tags": ("hard",), "note": "brand domain in the userinfo field"},
        )

    _fill(g, "userinfo_decoy", per_category, rng, at_trick)

    # ---- native-script impostors ------------------------------------------------
    def native_host(r: random.Random, _b: str):
        name, lang, script, words, tld = r.choice(_NATIVE)
        return (
            f"https://{name}-{r.choice(words)}.{tld}{r.choice(('/', '/login', '/verify'))}",
            {"lang": lang, "script": script},
        )

    _fill(g, "native_brand_host", per_category, rng, native_host)

    def native_path(r: random.Random, b: str):
        name, lang, script, words, _tld_ = r.choice(_NATIVE)
        return (
            f"https://{_rand_label(r)}.{_tld(r)}/{r.choice(words)}/{name}/{b}",
            {"lang": lang, "script": script, "tags": ("hard",)},
        )

    _fill(g, "native_brand_path", per_category, rng, native_path)

    def mixed(r: random.Random, b: str):
        _n, lang, script, words, _t = r.choice(_NATIVE)
        return (
            f"https://{b}-{r.choice(words)}.{_tld(r)}{r.choice(_LOGIN_PATHS)}",
            {"lang": lang, "script": f"Latn+{script}"},
        )

    _fill(g, "mixed_script_label", per_category, rng, mixed)
    return g.items


